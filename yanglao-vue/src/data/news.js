export const getNewsById = (id) => {
  const numericId = parseInt(id)
  return newsList.find(news => news.id === numericId)
}

export const getNewsByCategory = (category) => {
  if (category === 'all') return newsList
  return newsList.filter(news => news.category === category)
}

export const getHotNews = () => {
  return newsList.filter(news => news.isHot)
}

export const getRecommendedNews = () => {
  return newsList.filter(news => news.isRecommended)
}

export const searchNews = (keyword) => {
  if (!keyword) return newsList
  const lowerKeyword = keyword.toLowerCase()
  return newsList.filter(news =>
    news.title.toLowerCase().includes(lowerKeyword) ||
    news.excerpt.toLowerCase().includes(lowerKeyword) ||
    news.content.toLowerCase().includes(lowerKeyword) ||
    news.tags.some(tag => tag.toLowerCase().includes(lowerKeyword))
  )
}

